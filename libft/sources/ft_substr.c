#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*ptr;
	size_t	i;
	size_t	s_len;

	if (s == NULL)
		return (NULL);

	s_len = ft_strlen(s);

	i = 0;
	ptr = malloc(len + 1 * sizeof(char));
	
	if (ptr == NULL)
		return (NULL);
	
	while (i < len)
	{
		ptr[i] = s[start + i];
		i++;
	}
	ptr[i] = '\0';
	return (ptr);
}
